# Dictionary Example

student = {
    "name": "Khushi",
    "age": 20,
    "course": "BCA"
}
print(student)

print("Name:", student["name"])

student["city"] = "Jaipur"

print(student)

# Tuple Example

numbers = (10, 20, 30, 40)

print(numbers)

print(numbers[1])

print(len(numbers))

# Set Example

fruits = {"apple", "banana", "mango"}

print(fruits)

fruits.add("orange")

print(fruits)